import asyncio
from pathlib import Path

import pytest

from lantern.media import GIB, Preparation, Probe, needs_preparation, probe, tool_path


def test_codec_decision_is_capability_based():
    info = Probe("h264", "eac3", 10, "matroska")
    assert not needs_preparation(info, False, ["audio/eac3"], ".mkv")
    assert needs_preparation(info, False, ["audio/mp4a-latm"], ".mkv")
    assert needs_preparation(info, True, ["audio/eac3"], ".mkv")
    assert needs_preparation(info, False, ["audio/eac3"], ".avi")


async def test_storage_limit_and_unsupported_video(tmp_path):
    source = tmp_path / "movie.mkv"
    source.write_bytes(b"content")
    preparation = Preparation(tmp_path / "cache", quota=1)
    with pytest.raises(ValueError, match="video conversion"):
        await preparation.prepare(source, Probe("vp9", "aac", 10, "matroska"), lambda _: None)
    with pytest.raises(ValueError, match="10 GiB"):
        await preparation.prepare(source, Probe("h264", "aac", 10, "matroska"), lambda _: None)


async def test_real_audio_preparation_preserves_video_and_original(tmp_path):
    try:
        ffmpeg = tool_path("ffmpeg")
    except RuntimeError:
        pytest.skip("Run scripts/bootstrap.ps1 for FFmpeg integration test")
    source = tmp_path / "sample.mkv"
    process = await asyncio.create_subprocess_exec(ffmpeg, "-v", "error", "-f", "lavfi", "-i", "color=c=blue:s=320x180:r=24:d=2", "-f", "lavfi", "-i", "sine=frequency=440:duration=2", "-c:v", "h264_mf", "-c:a", "ac3", "-shortest", str(source), stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
    _, error = await process.communicate()
    if process.returncode:
        # The LGPL build may lack Media Foundation; use the fixture generated by setup.
        pytest.skip(f"No H.264 encoder available for synthetic fixture: {error.decode()[:120]}")
    original = source.read_bytes()
    info = await probe(source)
    progress = []
    preparation = Preparation(tmp_path / "cache")
    result = await preparation.prepare(source, info, progress.append)
    converted = await probe(result)
    assert converted.video == info.video == "h264"
    assert converted.audio == "aac"
    assert source.read_bytes() == original
    assert progress[-1] == 100
    preparation.cleanup()
    assert not result.exists()
