from lantern.media import GIB, Preparation, Probe, needs_preparation, playback_plan, probe, tool_path


def test_codec_decision_is_capability_based():
    info = Probe("h264", "eac3", 10, "matroska")
    assert not needs_preparation(info, False, ["audio/eac3"], ".mkv")
    assert needs_preparation(info, False, ["audio/mp4a-latm"], ".mkv")
    assert needs_preparation(info, True, ["audio/eac3"], ".mkv")
    assert needs_preparation(info, False, ["audio/eac3"], ".avi")


@pytest.mark.parametrize("info,cast,mimes,suffix,mode", [
    (Probe("h264", "aac", 10, "mp4", 2), True, [], ".mp4", "direct"),
    (Probe("h264", "aac", 10, "matroska", 2), True, [], ".mkv", "remux"),
    (Probe("h264", "aac", 10, "mp4", 6), True, [], ".mp4", "audio"),
    (Probe("h264", "ac3", 10, "matroska", 6), True, [], ".mkv", "audio"),
    (Probe("h264", "aac", 10, "avi", 2), False, ["audio/mp4a-latm"], ".avi", "remux"),
    (Probe(None, "mp3", 10, "mp3", 2), True, [], ".mp3", "direct"),
    (Probe(None, "pcm_s16le", 10, "wav", 2), False, ["audio/raw"], ".wav", "direct"),
])
def test_cheapest_compatible_media_plan(info, cast, mimes, suffix, mode):
    assert playback_plan(info, cast, mimes, suffix).mode == mode


async def test_storage_limit_and_unsupported_video(tmp_path):
    source = tmp_path / "movie.mkv"
    source.write_bytes(b"content")
    preparation = Preparation(tmp_path / "cache", quota=1)
    with pytest.raises(ValueError, match="video conversion"):
        await preparation.prepare(source, Probe("vp9", "aac", 10, "matroska"), lambda _: None)
    with pytest.raises(ValueError, match="session cache limit"):
        await preparation.prepare(source, Probe("h264", "aac", 10, "matroska"), lambda _: None)


@pytest.mark.parametrize("copy_audio,audio_codec", [(False, "ac3"), (True, "aac")])
async def test_real_audio_preparation_preserves_video_and_original(tmp_path, copy_audio, audio_codec):
    try:
        ffmpeg = tool_path("ffmpeg")
    except RuntimeError:
        pytest.skip("Run scripts/bootstrap.ps1 for FFmpeg integration test")
    source = tmp_path / "sample.mkv"
    process = await asyncio.create_subprocess_exec(ffmpeg, "-v", "error", "-f", "lavfi", "-i", "color=c=blue:s=320x180:r=24:d=2", "-f", "lavfi", "-i", "sine=frequency=440:duration=2", "-c:v", "h264_mf", "-c:a", audio_codec, "-shortest", str(source), stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
    _, error = await process.communicate()
    if process.returncode:
        # The LGPL build may lack Media Foundation; use the fixture generated by setup.
        pytest.skip(f"No H.264 encoder available for synthetic fixture: {error.decode()[:120]}")
    original = source.read_bytes()
    info = await probe(source)
    progress = []
    preparation = Preparation(tmp_path / "cache")
    result = await preparation.prepare(source, info, progress.append, copy_audio=copy_audio)
    converted = await probe(result)
    assert converted.video == info.video == "h264"
    assert converted.audio == "aac"
    assert source.read_bytes() == original
    assert progress[-1] == 100
    if copy_audio:
        async def audio_bytes(path):
            process = await asyncio.create_subprocess_exec(ffmpeg, "-v", "error", "-i", str(path), "-map", "0:a:0", "-c:a", "copy", "-f", "adts", "pipe:1", stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
            output, error = await process.communicate()
            assert process.returncode == 0, error.decode()
            return output
        assert await audio_bytes(source) == await audio_bytes(result)
    preparation.cleanup()
    assert not result.exists()


def test_cache_evicts_oldest_unused_files_and_preserves_playback(tmp_path):
    preparation = Preparation(tmp_path / "cache", quota=100)
    oldest, recent, active = [preparation.cache / f"{name}.mp4" for name in ("oldest", "recent", "active")]
    for path, size, timestamp in ((oldest, 20, 1), (recent, 20, 2), (active, 40, 3)):
        path.write_bytes(b"x" * size)
        os.utime(path, (timestamp, timestamp))
    preparation.pinned = {active}
    assert preparation.reserve(30) == 60
    assert not oldest.exists()
    assert recent.exists()
    assert active.exists()


def test_full_cache_never_evicts_files_used_by_decoder(tmp_path):
    preparation = Preparation(tmp_path / "cache", quota=100)
    active = preparation.cache / "active.mp4"
    active.write_bytes(b"x" * 80)
    preparation.pinned = {active}
    with pytest.raises(ValueError, match="still in playback"):
        preparation.reserve(30)
    assert active.exists()
